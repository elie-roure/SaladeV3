import { expect, test } from '@playwright/test'

test('invitation, comptes privés, partage et conflit entre deux appareils', async ({ page, browser }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/')
  await expect(page.locator('#email')).toBeVisible()
  expect((await page.request.get('/api/tournaments')).status()).toBe(401)
  await page.locator('#email').fill('admin@example.test')
  await page.locator('#password').fill('Test-only-password-123')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await page.getByRole('button', { name: 'Gérer les accès' }).click()
  const email = `organizer-${testInfo.project.name}@example.test`
  await page.locator('#invite-email').fill(email)
  await page.getByRole('button', { name: 'Créer le lien privé' }).click()
  await expect(page.locator('#invite-link')).toBeVisible()
  const invitation = await page.locator('#invite-link').inputValue()
  const context = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const organizer = await context.newPage()
    organizer.on('pageerror', error => errors.push(error.message))
    organizer.on('dialog', dialog => dialog.accept())
    await organizer.goto(invitation)
    await organizer.locator('#password').fill('Organizer-test-password-123')
    await organizer.locator('#password-confirmation').fill('Organizer-test-password-123')
    await organizer.getByRole('button', { name: 'Activer mon accès' }).click()
    await expect(organizer.locator('.account-bar')).toContainText(email)
    await expect(organizer.getByRole('button', { name: 'Gérer les accès' })).toHaveCount(0)
    expect((await organizer.request.get('/api/users')).status()).toBe(403)
    const title = `Tournoi partagé ${testInfo.project.name}`
    await organizer.locator('#tournament-name').fill(title)
    await organizer.getByRole('button', { name: 'Préparer le tournoi' }).click()
    await organizer.locator('#names').fill('Alice\nBob\nCamille\nDavid\nEmma')
    await organizer.locator('#courts').fill('1')
    await organizer.getByRole('button', { name: 'Créer le tournoi', exact: true }).click()
    await expect(organizer.getByText('Enregistré sur le serveur', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Actualiser la liste' }).click()
    await page.locator('.tournament-list li').filter({ hasText: title }).getByRole('button', { name: 'Ouvrir' }).click()
    await expect(page.locator('#tournament')).toBeVisible()
    await organizer.locator('#score-0-0').fill('5')
    await organizer.locator('#score-0-1').fill('25')
    await expect(organizer.getByText('Enregistré sur le serveur', { exact: true })).toBeVisible()
    await page.locator('#score-0-0').fill('30')
    await expect(page.getByRole('alert').first()).toContainText('autre organisateur')
    await expect(page.getByText('Non sauvegardé — exportez une copie', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Recharger depuis le serveur' }).click()
    await expect(page.locator('#score-0-0')).toHaveValue('5')
    await expect(page.locator('#score-0-1')).toHaveValue('25')
    await expect(page.locator('#encounters')).toContainText('1×')
    await page.getByRole('button', { name: 'Tous les tournois' }).click()
    // Le panneau administrateur était déjà ouvert avant d'ouvrir le tournoi.
    await page.locator('.account-list li').filter({ hasText: email }).getByRole('button', { name: 'Désactiver', exact: true }).click()
    expect((await organizer.request.get('/api/tournaments')).status()).toBe(401)
    await organizer.reload()
    await expect(organizer.locator('#email')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
  } finally { await context.close() }
})
